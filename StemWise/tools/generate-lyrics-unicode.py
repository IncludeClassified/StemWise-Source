"""Generate the display-word classifiers and library search folding from pinned Unicode contracts."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / 'StemWise/contracts/enrichment/lyrics-unicode-18.json'
PYTHON = ROOT / 'PC side/stemwise-playlist-builder/src/lyrics_unicode.py'
KOTLIN = ROOT / 'StemWise/app/src/main/java/app/stemwise/enrichment/LyricsUnicode.kt'
UNICODE_VERSION = '18.0.0'
SCRIPT_SOURCE_ROOT = f'https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/'
SOURCE = SCRIPT_SOURCE_ROOT + 'UnicodeData.txt'
SHA256 = '0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950'
SCRIPT_SOURCES = {
    'Scripts.txt': '0071fd81b6aeae25f6e8bce8efec3066a6476a91b49bdb2f52dc76e817862a6a',
    'ScriptExtensions.txt': '5c9d34a922f687726f2a8bcf57d49f905987e51f1b21b58c95a00fbe255cec23',
    'PropertyValueAliases.txt': '06c4c8eaf7b0bf34abe73b113da1215bd784ac254d4c223600b90267caa4bbbd',
}
FOLD_TABLE = ROOT / 'StemWise/contracts/search/case-fold-17.json'
FOLD_KOTLIN = ROOT / 'StemWise/app/src/main/java/app/stemwise/ui/SearchCaseFold.kt'
FOLD_SOURCE = 'https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt'
FOLD_SHA256 = 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183'


def curated_case_fold(data):
    if hashlib.sha256(data).hexdigest() != FOLD_SHA256:
        raise ValueError('Case folding input differs from the pinned Unicode 17 source')
    mappings = []
    for line in data.decode('utf-8').splitlines():
        content = line.split('#', 1)[0].strip()
        if not content:
            continue
        code, status, replacement, *_ = (part.strip() for part in content.split(';'))
        if status in ('C', 'F'):
            mappings.append([int(code, 16), ''.join(chr(int(value, 16)) for value in replacement.split())])
    return {'unicodeVersion': '17.0.0', 'sourceUrl': FOLD_SOURCE, 'sourceSha256': FOLD_SHA256,
            'mappings': mappings}


def case_fold_output(table):
    if (table['unicodeVersion'], table['sourceUrl'], table['sourceSha256']) != ('17.0.0', FOLD_SOURCE, FOLD_SHA256):
        raise ValueError('Unsupported case folding source contract')
    rows = table['mappings']
    if len({row[0] for row in rows}) != len(rows) or rows != sorted(rows):
        raise ValueError('Case folding mappings must have unique sorted code points')
    codes = ','.join(str(row[0]) for row in rows)
    replacements = ','.join(json.dumps(row[1], ensure_ascii=True) for row in rows)
    return ('package app.stemwise.ui\n\n'
            '// Generated by tools/generate-lyrics-unicode.py from Unicode 17 default full case folding.\n'
            'internal object SearchCaseFold {\n'
            f'    private val codes = intArrayOf({codes})\n'
            f'    private val replacements = arrayOf({replacements})\n'
            '    fun fold(text: String): String = buildString(text.length) {\n'
            '        var offset = 0\n'
            '        while (offset < text.length) {\n'
            '            val code = text.codePointAt(offset)\n'
            '            val index = codes.binarySearch(code)\n'
            '            if (index < 0) appendCodePoint(code) else append(replacements[index])\n'
            '            offset += Character.charCount(code)\n'
            '        }\n'
            '    }\n'
            '}\n')


def curated(data, script_inputs):
    for name, expected in SCRIPT_SOURCES.items():
        if hashlib.sha256(script_inputs[name]).hexdigest() != expected:
            raise ValueError(f'Script input differs from pinned Unicode {UNICODE_VERSION} source: '+name)
    def records(name):
        for line in script_inputs[name].decode('utf-8').splitlines():
            content = line.split('#', 1)[0].strip()
            if content:
                yield [part.strip() for part in content.split(';')]
    aliases = {row[1]: row[2] for row in records('PropertyValueAliases.txt') if row[0] == 'sc'}
    properties = {}
    for name in ('Scripts.txt', 'ScriptExtensions.txt'):
        for extent, names in records(name):
            bounds = [int(value, 16) for value in extent.split('..')]
            values = {aliases.get(value, value) for value in names.split()}
            values -= {'Common', 'Inherited', 'Unknown'}
            values = {'cjk' if value in {'Han', 'Hiragana', 'Katakana'} else value for value in values}
            script = '|'.join(sorted(values))
            for code in range(bounds[0], bounds[-1]+1):
                properties[code] = script

    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError(f'Unicode input differs from the pinned Unicode {UNICODE_VERSION} source')
    intervals, first = [], None
    scripts = ['']
    for line in data.decode('utf-8').splitlines():
        code, name, category, *_ = line.split(';')
        code = int(code, 16)
        if name.endswith(', First>'):
            first = (code, name, category)
            continue
        start = code
        if name.endswith(', Last>'):
            start, name, category = first
            first = None
        flags = 1 if category[0] in 'LN' else 4 if category[0] == 'M' else 0
        if not flags:
            continue
        if category[0] == 'N':
            flags |= 2
        for scalar in range(start, code+1):
            script = properties.get(scalar, '') if category[0] == 'L' else ''
            if script not in scripts:
                scripts.append(script)
            value = [scalar, scalar, flags, scripts.index(script)]
            if intervals and intervals[-1][1] + 1 == scalar and intervals[-1][2:] == value[2:]:
                intervals[-1][1] = scalar
            else:
                intervals.append(value)
    return {'unicodeVersion': UNICODE_VERSION, 'sourceUrl': SOURCE, 'sourceSha256': SHA256,
            'scriptSources': {name: {'url': SCRIPT_SOURCE_ROOT+name, 'sha256': digest} for name, digest in SCRIPT_SOURCES.items()},
            'scripts': scripts, 'ranges': intervals}


def outputs(table):
    rows = table['ranges']
    py = ('# Generated by StemWise/tools/generate-lyrics-unicode.py; edit the pinned contract.\n'
          f'from bisect import bisect_right\n\nUNICODE_VERSION = "{table["unicodeVersion"]}"\n'
          f'_SCRIPTS = {tuple(table["scripts"])!r}\n'
          f'_RANGES = {tuple(tuple(row) for row in rows)!r}\n'
          '_STARTS = tuple(row[0] for row in _RANGES)\n\n'
          'def classification(codepoint):\n'
          '    index = bisect_right(_STARTS, codepoint) - 1\n'
          '    if index < 0 or codepoint > _RANGES[index][1]:\n'
          '        return 0, None\n'
          '    row = _RANGES[index]\n'
          '    return row[2], frozenset(_SCRIPTS[row[3]].split("|")) if _SCRIPTS[row[3]] else None\n')
    chunks = [rows[index:index+128] for index in range(0, len(rows), 128)]
    kt = ('package app.stemwise.enrichment\n\n'
          '// Generated by tools/generate-lyrics-unicode.py; edit the pinned contract.\n'
          'internal object LyricsUnicode {\n'
          f'    const val VERSION = "{table["unicodeVersion"]}"\n'
          '    private val scripts = arrayOf(' + ','.join(json.dumps(s) for s in table['scripts']) + ')\n'
          '    private val ranges = arrayOf(' + ','.join(f'chunk{i}()' for i in range(len(chunks))) + ')\n'
          '    private fun rowIndex(code: Int): Int {\n'
          f'        var low = 0; var high = {len(rows)} - 1\n'
          '        while (low <= high) {\n'
          '            val mid = (low + high) ushr 1\n'
          '            val row = ranges[mid / 128]; val offset = (mid % 128) * 4\n'
          '            if (code < row[offset]) high = mid - 1\n'
          '            else if (code > row[offset + 1]) low = mid + 1\n'
          '            else return mid\n'
          '        }\n        return -1\n    }\n'
          '    fun flags(code: Int): Int {\n'
          '        val index = rowIndex(code)\n'
          '        return if (index < 0) 0 else ranges[index / 128][(index % 128) * 4 + 2]\n    }\n'
          '    fun script(code: Int): Set<String>? {\n'
          '        val index = rowIndex(code)\n'
          '        return if (index < 0) null else scripts[ranges[index / 128][(index % 128) * 4 + 3]].takeIf { it.isNotEmpty() }?.split("|")?.toSet()\n    }\n')
    for index, chunk in enumerate(chunks):
        kt += f'    private fun chunk{index}() = intArrayOf(' + ','.join(str(n) for row in chunk for n in row) + ')\n'
    return {PYTHON: py, KOTLIN: kt + '}\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--unicode-data', type=Path)
    parser.add_argument('--script-data-dir', type=Path)
    parser.add_argument('--case-fold-data', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.unicode_data:
        if args.check:
            parser.error('--check does not replace the source contract')
        if args.script_data_dir is None:
            parser.error('--unicode-data requires --script-data-dir for pinned Script/Script_Extensions inputs')
        script_inputs = {name: (args.script_data_dir/name).read_bytes() for name in SCRIPT_SOURCES}
        TABLE.write_text(json.dumps(curated(args.unicode_data.read_bytes(), script_inputs), separators=(',', ':')) + '\n', encoding='utf-8')
    if args.case_fold_data:
        if args.check:
            parser.error('--check does not replace the source contract')
        FOLD_TABLE.parent.mkdir(parents=True, exist_ok=True)
        FOLD_TABLE.write_text(json.dumps(curated_case_fold(args.case_fold_data.read_bytes()), separators=(',', ':')) + '\n',
                              encoding='utf-8', newline='\n')
    table = json.loads(TABLE.read_text(encoding='utf-8'))
    if (table['unicodeVersion'], table['sourceUrl'], table['sourceSha256']) != (UNICODE_VERSION, SOURCE, SHA256):
        raise ValueError('Unsupported Unicode source contract')
    if table.get('scriptSources') != {name: {'url': SCRIPT_SOURCE_ROOT+name, 'sha256': digest} for name, digest in SCRIPT_SOURCES.items()}:
        raise ValueError('Unsupported Unicode script source contract')
    generated = outputs(table)
    generated[FOLD_KOTLIN] = case_fold_output(json.loads(FOLD_TABLE.read_text(encoding='utf-8')))
    for path, content in generated.items():
        if args.check:
            if path.read_text(encoding='utf-8') != content:
                raise ValueError('Stale generated tokenizer table: ' + path.name)
        else:
            path.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
