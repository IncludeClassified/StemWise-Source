"""Generate shared language constants and the self-contained installed schema."""
from __future__ import annotations
import argparse
import json
import copy
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = ROOT / "StemWise/contracts/enrichment"
SCHEMA = CONTRACTS / "song-enrichment-v2.schema.json"
OUTPUT = ROOT / "StemWise/audio-engine/src/main/java/app/stemwise/EnrichmentLimits.kt"
NATIVE_OUTPUT = ROOT / "StemWise/audio-engine/src/main/cpp/native_engine/NativePlaybackLimits.h"
PYTHON_OUTPUT = ROOT / "PC side/stemwise-playlist-builder/src/enrichment_constants.py"
ANDROID_CONTRACT = ROOT / "StemWise/app/src/main/java/app/stemwise/enrichment/EnrichmentConstants.kt"
PLAYBACK_OUTPUT = ROOT / "StemWise/audio-engine/src/main/java/app/stemwise/PlaybackLimits.kt"

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    capacity = json.loads((ROOT / 'StemWise/contracts/audio/playback-capacity.json').read_bytes())
    targets, leases = capacity['maximumTargets'], capacity['additionalDecoderLeases']
    if capacity.get('schemaVersion') != 1 or type(targets) is not int or not 1 <= targets <= 61 or type(leases) is not int or leases < 0:
        raise ValueError('Invalid playback capacity contract')
    playback_text = ('package app.stemwise\n\n'
        '// Generated by tools/generate-contract-limits.py from contracts/audio/playback-capacity.json.\n'
        f'const val MAX_SELECTED_TARGETS = {targets}\n'
        f'const val MAX_PLAYABLE_STEM_COUNT = {targets + 1}\n'
        f'const val MAX_NATIVE_MUSIC_LANES = {targets + 2}\n'
        f'const val MAX_OPEN_AUDIO_DECODERS = {targets + 2 + leases}\n')
    source = SCHEMA.read_bytes()
    contract = json.loads(source)
    installed = json.loads((CONTRACTS / "installed-enrichment-v2.source.json").read_bytes())
    # Bundle shared references so schema consumers need no remote resolver.
    for key in ("source", "generator", "generatedAt"):
        ref = installed["properties"][key]["$ref"].split("#/")[1].split("/")
        value = contract
        for part in ref:
            value = value[part]
        installed["properties"][key] = copy.deepcopy(value)
    for key, source_key in (("nativeRecording", "nativeRecording"), ("sourceDescriptor", "sourceRecord")):
        installed["$defs"][key] = copy.deepcopy(contract["$defs"][source_key])
    installed["properties"]["lyrics"] = {"$ref": "#/$defs/lyrics"}
    pending = ["lyrics"]
    while pending:
        key = pending.pop()
        if key in installed["$defs"]:
            continue
        definition = copy.deepcopy(contract["$defs"][key])
        installed["$defs"][key] = definition
        def referenced_definitions(value):
            if isinstance(value, dict):
                for name, child in value.items():
                    if name == "$ref" and child.startswith("#/$defs/"):
                        yield child.removeprefix("#/$defs/")
                    else:
                        yield from referenced_definitions(child)
            elif isinstance(value, list):
                for child in value:
                    yield from referenced_definitions(child)
        pending.extend(referenced_definitions(definition))
    maximum = contract["$defs"]["analysis"]["properties"]["durationMs"]["maximum"]
    levels = contract["$defs"]["waveformLevel"]["properties"]["frameDurationMs"]["enum"]
    assert type(maximum) is int and maximum > 0 and levels and all(type(x) is int and x > 0 for x in levels)
    minimum = min(levels)
    maximum_bpm = contract["$defs"]["bpm"]["maximum"]
    maximum_native_beats = maximum * maximum_bpm // 60_000 + 1
    properties = contract["properties"]
    generator = contract["$defs"]["generator"]["properties"]
    recording = contract["$defs"]["nativeRecording"]["properties"]
    constants = {
        "FORMAT_VERSION": properties["formatVersion"]["const"],
        "KIND": properties["kind"]["const"],
        "PROVIDER": contract["$defs"]["sourceIdentity"]["properties"]["provider"]["const"],
        "GENERATOR_NAME": generator["name"]["const"],
        "GENERATOR_VERSION": generator["version"]["const"],
        "MAX_DURATION_MS": maximum,
        "MAX_RECORDING_TRACK_ID": recording["trackId"]["maximum"],
        "MAX_RECORDING_BYTES": recording["byteCount"]["maximum"],
        "CANONICAL_UTC_TIMESTAMP_PATTERN": properties["generatedAt"]["pattern"],
        "INSTALLED_SCHEMA_VERSION": installed["properties"]["schemaVersion"]["const"],
        "INSTALLED_KIND": installed["properties"]["kind"]["const"],
        "INSTALLED_CONTRACT_VERSION": installed["properties"]["install"]["properties"]["contractVersion"]["const"],
    }
    python_text = '# Generated by StemWise/tools/generate-contract-limits.py; edit the production schemas.\n'
    python_text += ''.join(f'{key} = {value!r}\n' for key, value in constants.items())
    python_text += f'WAVEFORM_LEVELS_MS = frozenset({tuple(levels)!r})\n'
    kotlin_names = {"FORMAT_VERSION": "ENRICHMENT_FORMAT_VERSION", "GENERATOR_NAME": "ENRICHMENT_GENERATOR_NAME",
        "GENERATOR_VERSION": "ENRICHMENT_GENERATOR_VERSION", "INSTALLED_SCHEMA_VERSION": "INSTALLED_ENRICHMENT_SCHEMA_VERSION",
        "INSTALLED_KIND": "INSTALLED_ENRICHMENT_KIND", "INSTALLED_CONTRACT_VERSION": "INSTALLED_ENRICHMENT_CONTRACT",
        "MAX_RECORDING_TRACK_ID": "MAX_RECORDING_TRACK_ID", "MAX_RECORDING_BYTES": "MAX_RECORDING_BYTES",
        "CANONICAL_UTC_TIMESTAMP_PATTERN": "CANONICAL_UTC_TIMESTAMP_PATTERN"}
    kotlin_text = 'package app.stemwise.enrichment\n\n// Generated by tools/generate-contract-limits.py; edit the production schemas.\n'
    for key, name in kotlin_names.items():
        value = constants[key]
        literal = json.dumps(value) if isinstance(value, str) else str(value) + ('L' if key.startswith('MAX_') else '')
        kotlin_text += f'internal const val {name} = {literal}\n'
    text = ("package app.stemwise\n\n"
        "// Generated by tools/generate-contract-limits.py from the current shared contract.\n"
        f"const val MAX_ENRICHMENT_DURATION_MS = {maximum}L\n"
        f"const val MAX_ENRICHMENT_PCM_FRAMES_48K = {maximum * 48_000 // 1000}L\n"
        f"const val MIN_WAVEFORM_FRAME_DURATION_MS = {minimum}L\n"
        f"const val MAX_WAVEFORM_DATA_CHARACTERS = {(maximum + minimum - 1) // minimum * 8}\n"
        f"const val MAX_NATIVE_BEAT_GRID_POINTS = {maximum_native_beats}\n"
        "val ENRICHMENT_WAVEFORM_FRAME_DURATIONS_MS: Set<Long> = java.util.Collections.unmodifiableSet(linkedSetOf(" + ", ".join(f"{x}L" for x in levels) + "))\n")
    native_text = ("#pragma once\n\n"
        "// Generated by tools/generate-contract-limits.py from the current shared contract.\n"
        "namespace stemwise::audio::engine {\n"
        f"inline constexpr unsigned kMaximumNativeBeatGridPoints = {maximum_native_beats}U;\n"
        "}\n")
    for output, content in ((OUTPUT, text), (NATIVE_OUTPUT, native_text), (PYTHON_OUTPUT, python_text),
            (ANDROID_CONTRACT, kotlin_text), (PLAYBACK_OUTPUT, playback_text), (CONTRACTS / 'installed-enrichment-v2.schema.json',
             json.dumps(installed, ensure_ascii=False, indent=2) + '\n')):
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated contract limits are stale: {output.name}")
        else:
            output.write_text(content, encoding="utf-8", newline="\n")
    if not args.check:
        subprocess.run([sys.executable, "-B", str(ROOT / "Test suite/host/document_contracts.py"), "--write"], check=True)
    print("Current contract limits agree: duration, waveform and native beat-grid capacity")

if __name__ == "__main__":
    main()
